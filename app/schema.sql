CREATE TABLE IF NOT EXISTS invoices (
    invoice_id VARCHAR PRIMARY KEY,
    account_id VARCHAR,
    account_name VARCHAR,
    contact_email VARCHAR,
    region VARCHAR,
    industry VARCHAR,
    plan VARCHAR,
    billing_cycle VARCHAR,
    seats INTEGER,
    currency VARCHAR,
    amount DOUBLE,
    amount_usd DOUBLE,
    discount_pct DOUBLE,
    status VARCHAR,
    payment_method VARCHAR,
    signup_date DATE,
    invoice_date DATE,
    churned BOOLEAN,
    csat_score DOUBLE,
    support_tickets INTEGER,
    list_price_usd DOUBLE,
    mrr_usd DOUBLE,
    is_recognized_revenue BOOLEAN,
    raw_plan VARCHAR,
    raw_status VARCHAR
);
